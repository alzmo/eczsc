export function getLesson(id: number) {
  return lessons.find((lesson) => lesson.id === id);
}

export function getChapter(id: number) {
  return chapters.find(({ range }) => id >= range[0] && id <= range[1]) ?? chapters[0];
}

export function getLessonTags(lesson: Lesson) {
  const title = lesson.title;
  const tags = new Set<string>();
  const rules: Array<[RegExp, string]> = [
    [/分型/, "分型"], [/笔/, "笔"], [/线段|分段/, "线段"], [/中枢/, "中枢"],
    [/背驰|背弛/, "背驰"], [/买卖点|买点|卖点/, "买卖点"], [/走势|图形/, "走势结构"],
    [/级别|区间套/, "级别"], [/MACD|均线/, "辅助工具"], [/风险|资金管理|防狼/, "风险管理"],
    [/操作|短线|持股|持币/, "操作"], [/心理|修炼|人生|学佛|聪明/, "交易心理"],
  ];
  rules.forEach(([pattern, tag]) => pattern.test(title) && tags.add(tag));
  if (!tags.size) tags.add(getChapter(lesson.id).title);
  return [...tags].slice(0, 3);
}

export function formatLessonNumber(id: number) {
  return String(id).padStart(3, "0");
}
